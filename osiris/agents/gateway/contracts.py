"""Provider-neutral governance contracts and canonical data structures."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field  # noqa: F401
from datetime import datetime, timezone
from enum import Enum
import hashlib
import json
from typing import Any, Mapping, Protocol, Sequence  # noqa: F401


def canonical_json(data: Any) -> str:
    """Serializes data into canonical deterministic JSON (RFC 8785 subset)."""
    if hasattr(data, "__dataclass_fields__"):
        data = asdict(data)
    elif isinstance(data, (set, frozenset)):
        data = sorted(list(data))
    elif isinstance(data, datetime):
        data = data.isoformat()
    return json.dumps(data, sort_keys=True, separators=(",", ":"), default=str)


def compute_sha256(payload: Any) -> str:
    """Computes SHA-256 digest string for arbitrary payloads."""
    if isinstance(payload, str):
        raw = payload.encode("utf-8")
    elif isinstance(payload, bytes):
        raw = payload
    else:
        raw = canonical_json(payload).encode("utf-8")
    return f"sha256:{hashlib.sha256(raw).hexdigest()}"


class ActionKind(str, Enum):
    """Canonical action kinds. Each value is also the capability that authorizes it."""
    READ_ONLY_ANALYSIS = "READ_ONLY_ANALYSIS"
    RETURN_STRUCTURED_PROPOSAL = "RETURN_STRUCTURED_PROPOSAL"
    REPLAY_FIXTURE = "REPLAY_FIXTURE"
    SESSION_STATE_WRITE = "SESSION_STATE_WRITE"   # agent-private state dir only
    WORKSPACE_WRITE = "WORKSPACE_WRITE"           # requires a bound HumanApproval
    SUBPROCESS_EXEC = "SUBPROCESS_EXEC"           # requires a bound HumanApproval


class RiskTier(int, Enum):
    """Deterministic capability risk tiers."""
    TIER_0_NO_RISK = 0        # In-memory, read-only analysis
    TIER_1_LOW_RISK = 1        # Replay fixture verification
    TIER_2_CONTROLLED = 2      # Sandboxed temporary read
    TIER_3_ELEVATED = 3        # Workspace modification (requires human grant)
    TIER_4_HIGH = 4            # Subprocess (requires human grant); network prohibited
    TIER_5_CRITICAL = 5        # Key/secret/sovereign authority (prohibited)


class BudgetClass(str, Enum):
    """Governed economic budget classes."""
    FREE_TIER = "FREE_TIER"
    FREE_TRIAL_RESERVE = "FREE_TRIAL_RESERVE"
    DEV_PROGRAM_PROMOTIONAL = "DEV_PROGRAM_PROMOTIONAL"
    PAID_EXPLICIT = "PAID_EXPLICIT"


@dataclass(frozen=True)
class ProposalProvenance:
    """Immutable provenance record of who proposed an action."""
    proposer_id: str
    provider: str
    backend: str
    model: str | None
    session_id: str | None
    route_ref: str


@dataclass(frozen=True)
class ActionTarget:
    """Typed canonical target of an action."""
    resource_type: str
    locator: str
    content_digest: str | None = None

    def digest(self) -> str:
        return compute_sha256(asdict(self))


@dataclass(frozen=True)
class ActionProposal:
    """Canonical proposal generated by an agent. Grants zero authority."""
    proposal_id: str
    request_id: str
    proposer_id: str
    action_kind: ActionKind
    capability: str
    target: ActionTarget
    arguments: Mapping[str, Any]
    provenance: ProposalProvenance
    evidence_refs: tuple[str, ...]
    created_at: datetime
    expires_at: datetime
    nonce: str
    schema_version: str = "action-proposal/v1"
    proposal_digest: str = ""

    def __post_init__(self) -> None:
        if not self.proposal_digest:
            payload = {
                "proposal_id": self.proposal_id,
                "request_id": self.request_id,
                "proposer_id": self.proposer_id,
                "action_kind": self.action_kind.value if isinstance(self.action_kind, ActionKind) else str(self.action_kind),
                "capability": self.capability,
                "target": asdict(self.target),
                "arguments": self.arguments,
                "provenance": asdict(self.provenance),
                "evidence_refs": list(self.evidence_refs),
                "created_at": self.created_at.isoformat(),
                "expires_at": self.expires_at.isoformat(),
                "nonce": self.nonce,
                "schema_version": self.schema_version,
            }
            object.__setattr__(self, "proposal_digest", compute_sha256(payload))


@dataclass(frozen=True)
class HumanApproval:
    """A human decision bound to exactly one proposal digest.

    Binding to the digest means an approval cannot be replayed onto a different
    target, different arguments, or a re-issued proposal with a fresh nonce.
    """
    approval_id: str
    proposal_digest: str
    approver_id: str
    channel: str
    approved_at: datetime

    @classmethod
    def for_proposal(
        cls,
        proposal: "ActionProposal",
        approver_id: str,
        channel: str = "tty",
        now: datetime | None = None,
    ) -> "HumanApproval":
        approved_at = now or datetime.now(timezone.utc)
        approval_id = "approval_" + compute_sha256(
            f"{proposal.proposal_digest}:{approver_id}:{approved_at.isoformat()}"
        )[7:23]
        return cls(
            approval_id=approval_id,
            proposal_digest=proposal.proposal_digest,
            approver_id=approver_id,
            channel=channel,
            approved_at=approved_at,
        )


@dataclass(frozen=True)
class AuthorizedAgentRequest:
    """Policy-bound request dispatched to an agent adapter."""
    request_id: str
    task: str
    allowed_capabilities: frozenset[str]
    data_classification: str
    authority_scope: str
    budget_class: BudgetClass = BudgetClass.FREE_TIER
    max_cost_usd: float = 0.0
    credit_id: str | None = None
    session_id: str | None = None


@dataclass(frozen=True)
class AgentResult:
    """Normalized result returned from an AgentAdapter."""
    request_id: str
    status: str
    provider: str
    proposals: tuple[ActionProposal, ...]
    usage: Mapping[str, Any]
    error: str | None = None
    output: str | None = None


@dataclass(frozen=True)
class ExecutionGrant:
    """Short-lived, tightly scoped token permitting an executor to run an action."""
    grant_id: str
    request_id: str
    proposal_hash: str
    allowed_action: ActionKind
    allowed_target_digest: str
    allowed_arguments_digest: str
    issued_at: datetime
    expires_at: datetime
    policy_version: str
    integrity_digest: str


class AgentAdapter(Protocol):
    """Provider-neutral protocol implemented by all agent backends."""
    def capabilities(self) -> frozenset[str]: ...
    async def run(self, request: AuthorizedAgentRequest) -> AgentResult: ...
